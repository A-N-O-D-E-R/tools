package com.anode.tool.document;

/**
 * Enumeration of API operations for document manipulation.
 */
public enum api {
	/**
	 * Delete path operation.
	 */
	DELETE_PATH,

	/**
	 * Get array size operation.
	 */
	GET_ARRAY_SIZE,

	/**
	 * Get array index operation.
	 */
	GET_ARRAY_INDEX,

	/**
	 * Get operation.
	 */
	GET,

	/**
	 * Set operation.
	 */
	SET,

	/**
	 * Get array value operation.
	 */
	GET_ARRAY_VALUE,

	/**
	 * Set array value operation.
	 */
	SET_ARRAY_VALUE,

	/**
	 * Path exists operation.
	 */
	PATH_EXISTS,

	/**
	 * Content operation.
	 */
	CONTENT
}
